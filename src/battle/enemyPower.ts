/**
 * 敵の攻撃力にだけ掛かる係数。
 *
 * 敵の強さは長らく powerScale ひとつで表していた。HP・攻撃・防御に同じ倍率が
 * 掛かるので、「硬くしたい」だけのつもりでも殺傷力まで一緒に上がる。
 * それでも成立していたのは、当時の軽減式 `防御 ÷ (防御 + 300)` が
 * 高い攻撃力を大きく削り落としていたから。
 *
 * 軽減を攻撃力との比で決めるように変えたことで、その緩衝がなくなった。
 * 同じ powerScale でも敵の一撃が通るようになり、装備ダンジョン1階の勝率が
 * 60%想定に対して23%まで落ちた。
 *
 * powerScale を下げると敵が柔らかくなって手応えごと消えるので、
 * **耐久と殺傷力を別々に触れるように**この係数を分けた。
 * ここを下げるのは「敵を弱くする」ことではなく、
 * 「殴り合いの長さを保ったまま、事故死だけを減らす」ことを意味する。
 */
// 0.78〜0.85 が難易度テスト16件すべてを満たす帯だったので、その中央に置いている。
// 下げすぎると装備なしでも装備ダンジョン1階を抜けてしまい(0.62で93%)、
// 上げすぎると序盤のボスと装備ダンジョン9階が想定より厳しくなる(0.92で3件不合格)
export const ENEMY_ATK_SCALE = 0.82;

/** 敵1体の攻撃力に、上の係数を掛けた値 */
export function scaledEnemyAtk(atk: number): number {
  return Math.max(1, Math.round(atk * ENEMY_ATK_SCALE));
}
