/**
 * モンスターの体表シェーダだけが使うGLSLの断片。
 *
 * `three/shaderChunks.ts` は闘技場(arena.ts)と共有しているノイズ関数の置き場で、
 * あちらは別の担当が触る。体表の「光の質」に関する定義はここへ分ける。
 *
 * **GLSLの予約語を識別子に使わないこと。** `patch` / `sample` / `filter` /
 * `input` / `output` / `active` / `common` / `partition` / `resource` は
 * どれもテッセレーションや将来拡張のために予約されていて、使うとコンパイルが落ちる。
 * TypeScript側の型チェックは文字列の中身を見ないので**素通りする**。
 * 実際に `patch` を変数名にしてフラグメントシェーダが停止し、
 * 体表が一切描かれなくなった事故がある。
 */

/**
 * 光の寒暖の割り。
 *
 * 参考にした高レアのカードで効いているのは明暗ではなく**色の転び**で、
 * 当たっている面は白く抜け、当たっていない面は青へ沈む。
 * 同じ明度差でも、色が転んでいるかどうかで「絵」か「露出不足の写真」かが決まる。
 *
 * 明るさの総量は増やさない。陰を青くするぶん明部を白くするだけなので、
 * ブルームへ投げ込む光は増えず、加算合成の飽和には効かない。
 */
export const SURFACE_LIGHT_CHUNK = /* glsl */ `
/** キーライトの色。温かい白。彩度を持たせすぎると全身が黄ばむ */
const vec3 KEY_TINT = vec3(1.000, 0.958, 0.884);
/** 冷たいフィル。空から回り込む青 */
const vec3 FILL_TINT = vec3(0.38, 0.48, 1.00);
/** 下を向いた面に返る、床の冷えた紫。ここが「暗部の色」の下限になる */
const vec3 SHADOW_LOW = vec3(0.062, 0.072, 0.146);
/** 上を向いた面に落ちる空の青。キーが当たらない上面はこの色で受ける */
const vec3 SHADOW_HIGH = vec3(0.138, 0.196, 0.392);

/**
 * 半球光。上は空の青、下は床から返る冷えた紫。
 *
 * **暗部は「暗い」のではなく「青い」。** 明度だけを落とすと、そこだけ
 * 彩度の抜けた灰色になり、形は読めても材質が読めなくなる。
 */
vec3 hemisphereAmbient(vec3 n) {
  return mix(SHADOW_LOW, SHADOW_HIGH, n.y * 0.5 + 0.5);
}

/**
 * 明部の色抜け。
 *
 * 強い光が当たった面は、地色の色味を保ったまま明るくなるのではなく、
 * 表面での一次反射が混ざって**白へ寄る**。これが無いと、どれだけ明度を上げても
 * 「濃い色のまま明るいだけ」の塗り絵に見える。
 *
 * 指数を高く取ってあるので出る面積はごく狭い。総量はほとんど増えない。
 */
vec3 highlightBleach(vec3 albedo, float lit) {
  return mix(albedo, vec3(1.0), 0.75) * pow(lit, 5.0);
}
`;
