/**
 * 枠の番号から、その枠の印を引く。
 *
 * 枠1/3/5は付くメインの数値が固定(攻撃力・防御力・HP)で、2/4/6は抽選。
 * 印もそれに合わせてある。剣・盾・兜が固定の3つ、羽・珠・環が可変の3つ。
 */
export function slotIcon(slot: number): IconName {
  const n = Math.min(6, Math.max(1, Math.round(slot)));
  return `slot${n}` as IconName;
}

