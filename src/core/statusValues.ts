/**
 * **通常のバフ・デバフの効果量。ここが唯一の置き場所。**
 *
 * 同じ名前・同じアイコンの強化/弱体は、スキルが違っても**必ず同じ量**にする。
 * 以前はスキルごとに直書きしていたため、「味方全体の攻撃力を上昇させる」という
 * 同じ文言なのに +30% / +40% / +45% / +50% が混在し、
 * **プレイヤーからは区別できないのに強さが違う**状態になっていた
 * (`docs/status-effect-audit.md` に全件の監査がある)。
 *
 * ## 量だけを固定する。持続ターンは固定しない
 *
 * 1T/2T/3T/4T といった**持続はスキルごとの個性**なので、ここでは決めない。
 * 付与確率・クールタイム・攻撃倍率も同じくスキル側のまま。
 *
 * ## バフが低く、デバフが高いのは意図どおり
 *
 * バフは基本的に確定で入る。デバフは付与確率・効果抵抗・免疫の3つを抜けないと入らない。
 * 通す手間がそのまま効果量の差になっている。
 *
 * ## 防御DOWNが-75%と大きい理由
 *
 * 防御計算が `1000/(1000+1.2×DEF)` になり、**軽減率がDEFの値だけで決まる**ようになった。
 * 攻撃を積んでも相手の防御は抜けないので、通す手段は防御無視か防御低下しかない。
 * -50%のままでは「妨害役を1枠使う」だけの見返りが出ない。
 */

