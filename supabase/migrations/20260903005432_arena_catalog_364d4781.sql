--
-- アリーナ: 照合用のゲーム定義
--
-- **このファイルは生成物です。手で書き換えないでください。**
--   npx tsx tools/exportArenaCatalog.mts
--
-- 防衛編成をサーバが検分するための表。ここに無い図鑑ID・属性・
-- メインOP・潜在覚醒は、すべて拒否されます。
-- 値の上限は式を書き写さず、生成器そのものを回して測ってあります。
--

create table if not exists public.arena_catalog_monsters (
  dex_id      text primary key,
  template_id text not null,
  element     text not null
);

create table if not exists public.arena_catalog_latents (
  dex_id    text not null,
  latent_id text not null,
  primary key (dex_id, latent_id)
);

create table if not exists public.arena_catalog_slot_mains (
  slot      smallint not null,
  stat_type text     not null,
  primary key (slot, stat_type)
);

-- メインOP・サブOPが到達しうる最大値。**これを超える装備は存在しない**
create table if not exists public.arena_catalog_stat_caps (
  stat_type text     not null,
  star      smallint not null,
  level     smallint not null,
  main_max  numeric  not null,
  sub_max   numeric  not null,
  primary key (stat_type, star, level)
);

create table if not exists public.arena_catalog_star_rules (
  star           smallint primary key,
  max_level      smallint not null,
  ability_points integer  not null
);

create table if not exists public.arena_catalog_sets (
  set_type text primary key
);

create table if not exists public.arena_catalog_limits (
  key   text    primary key,
  value numeric not null
);

