/** そのレートの帯。表の外の値でも必ず1つ返す */
export function arenaNpcBandForRating(rating) {
    let found = ARENA_NPC_BANDS[0];
    for (const band of ARENA_NPC_BANDS) {
        if (rating >= band.minRating)
            found = band;
    }
    return found;
}
