/**
 * 試練の塔80階「古代聖竜」第3回。**本編には1行も入っていない。**
 *
 * ## V2で分かったこと
 *
 * V2は狙いと逆になった。**お供を倒す線ほど負ける**(最良16.9%)一方で、
 * 雑な「ボス集中」が35.7%で最高。切り分けの結果、難易度を作っていたのは
 * 免疫ではなく**鼓舞晶のバフとゲージ加速**だった
 * (2つで勝率が15.7〜37.8pt動き、免疫まわり4つの合計を上回る)。
 *
 * ## V3で変える2つ
 *
 *   1. **鼓舞晶を弱める。**消さずに効き幅を落とす
 *      (S2 ATK+40%/SPD+30% → +32%/+22%、S3 ゲージ+20% → +16%)。
 *      弱め幅は3段階を測って選んだ——**強く弱めるほどボス集中が得をする**ので、
 *      ボス集中が目標レンジに収まる「小」を採る
 *   2. **お供を1体倒すごとに、ボスの被ダメージ+5%**(最大+20%)
 *
 * 2つ目が肝。V2ではお供の合計HP410,000(ボス単体の2倍超)を削っても、
 * 見返りが「その1体の火力が消える」だけで、払う手数に見合っていなかった。
 * **倒したことがボス撃破そのものを楽にする**形にして、
 * 「お供を倒す攻略に意味がある」を成立させにいく。
 *
 * この上乗せは**免疫中でも効く**。免疫中だけ消えるなら、
 * ボスが免疫を張っている間はお供を倒した意味が無くなり、V2へ逆戻りする。
 */
import type { Scenario } from "../types.js";
import { buildTower80V2, type Tower80Variant } from "./tower80v2.js";
import { TOWER80_RULES } from "../tower80/probe.js";

/**
 * V3の確定値。**測定の途中で動かさない。**
 *
 * 鼓舞晶の弱め幅は3段階(小/中/大)を1000戦ずつ振って選んだ。
 * **「小」だけがボス集中を目標レンジ(40〜55%)に収める。**
 *
 *   小 …… お供線 最良27.2% / ボス集中 **48.1%** ←これ
 *   中 …… お供線 最良32.9% / ボス集中 64.9%
 *   大 …… お供線 最良39.3% / ボス集中 72.8%
 *
 * 弱めるほどお供線も伸びるが、**ボス集中の伸びの方が大きい**。
 * 鼓舞晶はボスを削る邪魔をしているので、外すと
 * 「ボスだけ削ればいい線」が一番得をする。
 */
export const TOWER80_V3_VARIANT: Tower80Variant = {
  inspireProfile: "LIGHT",
  escortKillDamageBonus: TOWER80_RULES.escortKillDamageBonus,
};

export function buildTower80V3(extra: Tower80Variant = {}): Scenario {
  const scenario = buildTower80V2({ ...TOWER80_V3_VARIANT, ...extra });
  return {
    ...scenario,
    id: "tower-80-v3",
    title: "試練の塔80階 免疫5体編成 第3回",
    note: "V2から鼓舞晶を弱め(S2 ATK+32%/SPD+22%、S3 ゲージ+16%)、"
      + "お供1体撃破ごとにボスの被ダメージ+5%(最大+20%、免疫中も効く)を追加した案。",
  };
}

export const TOWER80_V3: Scenario = buildTower80V3();
